#!/usr/bin/env python3
"""Complete rc.3 release bookkeeping without weakening existing tests.

Temporary release recipe. Retired generated bytes stay pinned in Git history;
all pre-0.14 source trees and historical evidence records remain unchanged.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OLD = '0.14.0-rc.2'
NEW = '0.14.0-rc.3'
BASE = 'c1019b6253e5906b315c8eaa31413ff5acca3605'
RETIRED = 'SAFOR-FRAMEWORK-v0.14.0-rc.2.json'
RETIRED_SHA = '165570e46c96730cc7853ab17146dd1d2cfb991c'
TEST_PINS = {
    'tests/test_v014_release.py': '5f9bce3a39ea9446e77ffaba4c6499233ae15f63',
    'tests/test_v014_bundle_integration.py': 'c2de789b0dde4d9c7fc2215470acb90d742fedc4',
    'tests/test_human_notice_conformance.py': 'dc7a51a370ea64116143bd0ac95ef62e4f5824e4',
    'tests/test_user_onboarding.py': '1f8838e68a6fe51a64aabb4d84132a62c97850d6',
}
ARTIFACTS = ['SAFOR-FRAMEWORK.json', f'SAFOR-FRAMEWORK-v{NEW}.json',
             'SAFOR-FRAMEWORK-WEBSITE.json', 'SAFOR-FRAMEWORK-SAAS.json',
             'SAFOR-FRAMEWORK-BOOK-CREATION.json', 'SAFOR-TEST-ACCESS-SAAS.json',
             'SAFOR-TEST-ACCESS-BOOK-CREATION.json']


def blob_sha(raw):
    return hashlib.sha1(f'blob {len(raw)}\0'.encode() + raw).hexdigest()


def prepare():
    if (ROOT / 'VERSION').read_text().strip() != NEW:
        raise ValueError('Expected source correction to set rc.3 first.')
    for name, sha in {**TEST_PINS, RETIRED: RETIRED_SHA}.items():
        if blob_sha((ROOT / name).read_bytes()) != sha:
            raise ValueError(f'Unexpected baseline bytes: {name}')
    if (ROOT / RETIRED).read_bytes() != (ROOT / 'SAFOR-FRAMEWORK.json').read_bytes():
        raise ValueError('Refuse to retire a non-duplicate generated bundle.')
    for name in TEST_PINS:
        path = ROOT / name
        text = path.read_text()
        if text.count(OLD) != 1:
            raise ValueError(f'Unexpected version anchor count: {name}')
        path.write_text(text.replace(OLD, NEW))
    # Repository policy retains only the current generated root bundle.
    # Its exact previous content is preserved at BASE and RETIRED_SHA.
    (ROOT / RETIRED).unlink()
    path = ROOT / f'RELEASE-NOTES-{NEW}.md'
    text = path.read_text().replace(
        'Historical versioned bundles and pre-0.14 sources remain unchanged.',
        'Pre-0.14 sources remain unchanged. Previous release bytes remain unchanged '
        'in pinned Git history; the superseded generated root bundle is retired '
        'according to the existing repository-retention policy.')
    path.write_text(text)
    print('Updated four version-bound tests; retired only the verified duplicate root bundle.')


def artifacts():
    return [{'path': name, 'sha256': hashlib.sha256((ROOT / name).read_bytes()).hexdigest()}
            for name in ARTIFACTS]


def record(final):
    path = ROOT / f'RELEASE-EVIDENCE-{NEW}.json'
    if final:
        data = json.loads(path.read_text())
        if data.get('automatedTests', {}).get('result') != 'PASS':
            raise ValueError('Finalization requires actual unittest PASS evidence.')
    else:
        data = {'format': 'SAFOR_RELEASE_EVIDENCE', 'schemaVersion': '1.0',
                'version': NEW, 'status': 'PENDING_VERIFICATION',
                'automatedTests': {'result': 'NOT_RUN'},
                'projectMigration': 'NOT_PERFORMED'}
    data['artifacts'] = artifacts()
    data['historicalArtifacts'] = 'PRESERVED_IN_PINNED_GIT_HISTORY'
    data['retiredGeneratedRootBundle'] = {
        'path': RETIRED, 'sourceCommit': BASE, 'blobSha': RETIRED_SHA,
        'contentRewritten': False,
        'reason': 'Existing repository policy allows only the current root distribution.'}
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    (ROOT / f'SHA256SUMS-{NEW}.txt').write_text(
        ''.join(f"{a['sha256']}  {a['path']}\n" for a in data['artifacts']))
    print('Final evidence completed.' if final else 'Checksums prepared; test status remains NOT_RUN.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--prepare', action='store_true')
    group.add_argument('--checksums', action='store_true')
    group.add_argument('--finalize', action='store_true')
    args = parser.parse_args()
    if args.prepare:
        prepare()
    else:
        record(args.finalize)
