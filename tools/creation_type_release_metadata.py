#!/usr/bin/env python3
"""Separate prepared release metadata from observed successful test evidence."""
import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OLD, NEW = "0.14.0-rc.2", "0.14.0-rc.3"
TEST_PINS = {
    "tests/test_human_notice_conformance.py": "dc7a51a370ea64116143bd0ac95ef62e4f5824e4",
    "tests/test_v014_bundle_integration.py": "c2de789b0dde4d9c7fc2215470acb90d742fedc4",
    "tests/test_v014_release.py": "5f9bce3a39ea9446e77ffaba4c6499233ae15f63",
    "tests/test_user_onboarding.py": "1f8838e68a6fe51a64aabb4d84132a62c97850d6",
}


def blob(raw):
    return hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()


def prepare():
    for path, expected in TEST_PINS.items():
        if blob((ROOT / path).read_bytes()) != expected:
            raise ValueError(f"Test baseline changed: {path}")
    prior = ROOT / f"SAFOR-FRAMEWORK-v{OLD}.json"
    if blob(prior.read_bytes()) != "165570e46c96730cc7853ab17146dd1d2cfb991c":
        raise ValueError("Previous release blob changed")
    for path in TEST_PINS:
        p = ROOT / path
        text = p.read_text()
        old = f'VERSION = "{OLD}"'
        new = f'VERSION = "{NEW}"'
        if path.endswith("test_user_onboarding.py"):
            old, new = f'self.assertIn("v{OLD}", self.readme)', f'self.assertIn("v{NEW}", self.readme)'
        if text.count(old) != 1:
            raise ValueError(f"Expected one release version assertion: {path}")
        p.write_text(text.replace(old, new, 1))
    # Match existing repository retention policy: old generated bytes stay in Git history.
    prior.unlink()
    notes = ROOT / f"RELEASE-NOTES-{NEW}.md"
    notes.write_text(notes.read_text().replace("Historical versioned bundles and evidence are preserved.", "The previous generated bundle remains available at baseline commit c1019b6253e5906b315c8eaa31413ff5acca3605; historical release evidence and notes remain unchanged."))
    files = ["SAFOR-FRAMEWORK.json", f"SAFOR-FRAMEWORK-v{NEW}.json", "SAFOR-FRAMEWORK-WEBSITE.json", "SAFOR-FRAMEWORK-SAAS.json", "SAFOR-FRAMEWORK-BOOK-CREATION.json", "SAFOR-TEST-ACCESS-SAAS.json", "SAFOR-TEST-ACCESS-BOOK-CREATION.json"]
    artifacts = [{"path": p, "sha256": hashlib.sha256((ROOT / p).read_bytes()).hexdigest()} for p in files]
    (ROOT / f"SHA256SUMS-{NEW}.txt").write_text("".join(f"{a['sha256']}  {a['path']}\n" for a in artifacts))
    evidence = {"format": "SAFOR_CREATION_TYPE_REPAIR_EVIDENCE", "schemaVersion": "1.0", "version": NEW, "status": "PREPARED_TESTS_PENDING", "baselineCommit": "c1019b6253e5906b315c8eaa31413ff5acca3605", "artifacts": artifacts, "commandsPassed": [], "claims": {"projectMigrationCompleted": False, "agentsActivated": False, "releasePublished": False, "realGitMigrationE2E": "NOT_EXECUTED", "crossHostEvidence": "NOT_EXECUTED"}, "previousVersionRetention": {"mode": "IMMUTABLE_GIT_HISTORY", "commit": "c1019b6253e5906b315c8eaa31413ff5acca3605", "path": f"SAFOR-FRAMEWORK-v{OLD}.json", "blobSha": "165570e46c96730cc7853ab17146dd1d2cfb991c"}}
    (ROOT / f"RELEASE-EVIDENCE-{NEW}.json").write_text(json.dumps(evidence, indent=2) + "\n")


def finalize():
    path = ROOT / f"RELEASE-EVIDENCE-{NEW}.json"
    evidence = json.loads(path.read_text())
    if evidence["status"] != "PREPARED_TESTS_PENDING":
        raise ValueError("Unexpected release evidence state")
    evidence["status"] = "AUTOMATED_VALIDATION_PASS"
    evidence["evaluatedAt"] = datetime.now(timezone.utc).isoformat()
    evidence["commandsPassed"] = ["python tools/build_bundle.py --check", "python tools/build_domain_framework.py --check", "python tools/validate_safor.py", "python -m unittest discover -s tests -v"]
    path.write_text(json.dumps(evidence, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--finalize", action="store_true", help="Only after all declared validation commands passed")
    args = parser.parse_args()
    finalize() if args.finalize else prepare()
